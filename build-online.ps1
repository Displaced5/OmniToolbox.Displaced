param(
    [Parameter(Mandatory=$true)][string]$OmniDir,
    [string]$DalamudDir = $env:DALAMUD_HOME,
    [string]$DotnetPath = 'dotnet'
)
$ErrorActionPreference = 'Stop'
if (-not $DalamudDir) { throw '请使用 -DalamudDir 或 DALAMUD_HOME 指定匹配的 Dalamud API 15 程序集' }
$sourceRoot = $PSScriptRoot
$outputRoot = [IO.Path]::GetFullPath((Join-Path $sourceRoot '..\..\插件\OmniToolbox.Displaced'))
[void][IO.Directory]::CreateDirectory((Join-Path $outputRoot '.build\offline-source'))
foreach ($dependency in @('OmniToolbox.Common.dll','TreeTools.dll')) {
    if (-not (Test-Path -LiteralPath (Join-Path $OmniDir $dependency))) { throw "缺少 Omni 依赖：$dependency" }
}

# Deliver one self-contained source file; Omni compiles each online .cs independently.
$inputs = @('src/Core/Models.cs','src/Core/SettingsData.cs','src/Core/RestoreController.cs',
    'src/Core/EquipmentChangeTracker.cs','src/Core/SubmissionArbiter.cs','src/Core/FacewearEquipCommand.cs',
    'src/Core/MemoryArchive.cs','src/GameAdapter.cs','omni/ModuleServices.cs','omni/OnlineTexts.cs','omni/ClothingPairingOnline.cs')
$usings = [Collections.Generic.SortedSet[string]]::new([StringComparer]::Ordinal)
foreach ($line in @('using System;','using System.IO;','using System.Linq;','using System.Collections.Generic;')) { [void]$usings.Add($line) }
$bodies = foreach ($relative in $inputs) {
    $text = [IO.File]::ReadAllText((Join-Path $sourceRoot $relative)).Replace("`r`n","`n")
    $fileUsings = @([regex]::Matches($text, '(?m)^using [^\r\n]+;\s*$') | ForEach-Object { $_.Value.Trim() })
    $text = [regex]::Replace($text, '(?m)^using [^\r\n]+;\s*$', '')
    $namespace = [regex]::Match($text, '(?m)^namespace ([A-Za-z0-9_.]+);$')
    if (!$namespace.Success) { throw "不支持的源码命名空间：$relative" }
    $text = $text.Remove($namespace.Index, $namespace.Length).Trim()
    "// $relative`nnamespace $($namespace.Groups[1].Value)`n{`n$($fileUsings -join "`n")`n$text`n}`n"
}
$moduleText = "// Generated by build-online.ps1 from shared source and the Omni adapter.`n// Edit src/ and omni/ inputs, then regenerate this file and its manifest hash.`n#nullable enable`n" +
    (($usings | ForEach-Object { $_ }) -join "`n") + "`n`n" + ($bodies -join "`n")
$moduleDirectory = Join-Path $sourceRoot 'Modules'
[void][IO.Directory]::CreateDirectory($moduleDirectory)
$modulePath = Join-Path $moduleDirectory 'ClothingPairingOnline.cs'
[IO.File]::WriteAllText($modulePath, $moduleText, [Text.UTF8Encoding]::new($false))

& $DotnetPath build (Join-Path $sourceRoot 'omni\ClothingPairingOnline.csproj') -c Release "-p:DalamudDir=$DalamudDir" "-p:OmniDir=$OmniDir" -p:UseSharedCompilation=false -v:minimal
if ($LASTEXITCODE) { throw '在线模块编译检查失败，不更新清单' }
$moduleHash = (Get-FileHash -LiteralPath $modulePath).Hash.ToUpperInvariant()
$manifest = [ordered]@{
    SchemaVersion = 1
    Modules = @([ordered]@{
        InternalName='ClothingPairingOnline'; Author='Displaced'
        RepositoryURL='https://github.com/Displaced5/OmniToolbox.Displaced'
        Version='1.2.2'; ApiVersion=1; MinimumOmniVersion='1.2.0.6'
        File='Modules/ClothingPairingOnline.cs'; Sha256=$moduleHash
        Localization=[ordered]@{Source=[ordered]@{Title='自动装配面部、时尚配饰';Description='分别记忆一件时尚配饰和面部配饰，在出本或职业、套装切换造成缺失后恢复。'}}
    })
}
$json = ($manifest | ConvertTo-Json -Depth 8).Replace("`r`n","`n") + "`n"
[IO.File]::WriteAllText((Join-Path $sourceRoot 'TreeHouseModules.json'), $json, [Text.UTF8Encoding]::new($false))

foreach ($project in @('tests\ClothingPairing.Tests.csproj','omni-tests\ClothingPairing.OnlineChecks.csproj')) {
    & $DotnetPath build (Join-Path $sourceRoot $project) -c Release "-p:DalamudDir=$DalamudDir" -p:UseSharedCompilation=false -v:minimal
    if ($LASTEXITCODE) { throw "检查构建失败：$project" }
}
$binaries = Join-Path $outputRoot '.build\bin'
$coreChecks = & $DotnetPath (Join-Path $binaries 'ClothingPairing.Tests\Release\net10.0-windows\ClothingPairing.Tests.dll')
if ($LASTEXITCODE) { throw '恢复逻辑检查失败' }
$coreChecks | ForEach-Object { Write-Host $_ }
$onlineChecks = & $DotnetPath (Join-Path $binaries 'ClothingPairing.OnlineChecks\Release\net10.0-windows\ClothingPairing.OnlineChecks.dll') (Join-Path $binaries 'ClothingPairingOnline\Release\net10.0-windows\ClothingPairingOnline.dll') $OmniDir $DalamudDir $sourceRoot
if ($LASTEXITCODE) { throw 'Omni 真实契约检查失败' }
$onlineChecks | ForEach-Object { Write-Host $_ }
$onlineOutput = Join-Path $outputRoot '1.2.2'
[void][IO.Directory]::CreateDirectory($onlineOutput)
Copy-Item -LiteralPath $modulePath -Destination $onlineOutput -Force
Copy-Item -LiteralPath (Join-Path $sourceRoot 'TreeHouseModules.json') -Destination $onlineOutput -Force
$record = [ordered]@{
    version='1.2.2'; api=1; minimum_omni='1.2.0.6'; source_sha256=$moduleHash
    build='0 warnings, 0 errors'; core_checks=@($coreChecks); omni_checks=@($onlineChecks)
    host_assemblies=@(foreach ($name in @('OmniToolbox.Common.dll','TreeTools.dll')) {
        $file = Get-Item -LiteralPath (Join-Path $OmniDir $name)
        @{name=$name;version=$file.VersionInfo.ProductVersion;sha256=(Get-FileHash -LiteralPath $file.FullName).Hash}
    })
    in_game_verified=$false; installed=$false
}
$record | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath (Join-Path $onlineOutput '验证记录-1.2.2.json') -Encoding utf8
Write-Host "Omni 在线源文件：$modulePath"
Write-Host "SHA256：$moduleHash"
